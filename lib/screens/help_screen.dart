/// In-app guide and general-use terms for HPLeila.
class HelpScreen extends StatefulWidget {
  final int initialTab;
  const HelpScreen({super.key, this.initialTab = 0});

  @override
  State<HelpScreen> createState() => _HelpScreenState();
}

class _HelpScreenState extends State<HelpScreen>
    with SingleTickerProviderStateMixin {
  late final TabController _tabs;

  @override
  void initState() {
    super.initState();
    _tabs = TabController(
      length: 3,
      vsync: this,
      initialIndex: widget.initialTab.clamp(0, 2),
    );
  }

  @override
  void dispose() {
    _tabs.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) => Scaffold(
        appBar: AppBar(
          title: const Text('راهنما و اطلاعات حقوقی'),
          bottom: TabBar(
            controller: _tabs,
            isScrollable: true,
            tabs: const [
              Tab(icon: Icon(Icons.help_outline), text: 'راهنما'),
              Tab(icon: Icon(Icons.gavel_outlined), text: 'شرایط استفاده'),
              Tab(icon: Icon(Icons.copyright), text: 'حق نشر'),
            ],
          ),
        ),
        body: TabBarView(
          controller: _tabs,
          children: const [_GuideTab(), _TermsTab(), _CopyrightTab()],
        ),
      );
}

